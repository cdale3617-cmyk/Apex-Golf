import { test } from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';

test('play screen shares shot, ball and target state across navigation and persisted storage', async () => {
  const dom = new JSDOM('<!doctype html><html><body></body></html>', {url:'http://localhost'});
  for (const name of ['window','document','localStorage','HTMLElement','SVGElement','Event','MouseEvent']) Object.defineProperty(globalThis,name,{value:(dom.window as any)[name],configurable:true,writable:true});
  Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true,writable:true});
  Object.defineProperty(globalThis,'IS_REACT_ACT_ENVIRONMENT',{value:true,configurable:true,writable:true});
  (dom.window as any).PointerEvent=class extends dom.window.MouseEvent { pointerId:number; constructor(type:string,init:any={}){super(type,init);this.pointerId=init.pointerId??0;} };
  (globalThis as any).DOMPoint=class { constructor(public x:number,public y:number){} matrixTransform(){return this;} };
  (dom.window.SVGElement.prototype as any).setPointerCapture=()=>{};
  (dom.window.SVGElement.prototype as any).getScreenCTM=()=>({inverse:()=>({})});
  globalThis.fetch=async()=>{throw new Error('Offline test');};
  const box=(x:number,y:number,w:number,h:number)=>[[x,y],[x+w,y],[x+w,y+h],[x,y+h]];
  const h={id:'h1',courseId:'c',number:1,par:5,handicap:1,centerM:500,frontM:490,backM:510,windKmh:15,windDir:'N',tempC:20,elevationM:0,bearing:0,mapBearing:0,tee:{lat:-23,lon:150},weatherAt:Date.now(),slopeKnown:true,shape:{path:[[0,0],[0,500]],green:box(-10,490,20,20),fairways:[],water:[box(-40,195,80,45)],bunkers:[]}};
  localStorage.setItem('apex.data.v1',JSON.stringify({courses:[{id:'c',name:'Test course',lat:-23,lon:150,wxAt:Date.now()}],holes:[h,{...h,id:'h2',number:2}],clubs:[['Driver',220],['7 iron',140],['Wedge',80]].map(([name,carryM])=>({id:name,name,type:'Iron',carryM,totalM:Number(carryM)+10,loft:30})),rounds:[{id:'r',courseId:'c',date:'2026-11-08',status:'In progress'}],shots:[],scores:[],profile:null}));
  const React=await import('react');
  const {render,fireEvent,cleanup}=await import('@testing-library/react');
  const Play=(await import('../src/pages/Play')).default;
  const ui=render(React.createElement(Play,{go:()=>{}}));
  try {
    assert.ok(ui.getByRole('heading',{name:'7 iron',exact:true}));
    assert.ok(ui.getByRole('img',{name:'Compass showing the hole line and the wind'}));
    assert.ok(ui.getByLabelText('Wind 15 kilometres per hour from N'));
    fireEvent.click(ui.getByRole('button',{name:'Shot played',exact:true}));
    assert.ok(ui.getByRole('heading',{name:'Where is your ball?',exact:true}));
    fireEvent.click(ui.getByRole('button',{name:'Set ball on map',exact:true}));
    fireEvent.pointerDown(ui.getByRole('img',{name:/^Hole 1/}),{clientX:160,clientY:150,buttons:1,pointerId:1});
    fireEvent.pointerUp(ui.getByRole('img',{name:/^Hole 1/}),{clientX:160,clientY:150,pointerId:1});
    const saved=()=>JSON.parse(localStorage.getItem('apex.data.v1')!);
    assert.equal(saved().playing['r:h1'].shot,2);assert.equal(saved().playing['r:h1'].source,'map');
    assert.ok(saved().playing['r:h1'].ball[1]>300);
    fireEvent.click(ui.getByRole('button',{name:'Move yellow target',exact:true}));
    fireEvent.pointerDown(ui.getByRole('img',{name:/^Hole 1/}),{clientX:160,clientY:80,buttons:1,pointerId:2});
    fireEvent.pointerUp(ui.getByRole('img',{name:/^Hole 1/}),{clientX:160,clientY:80,pointerId:2});
    assert.ok(saved().playing['r:h1'].target);
    const ball= saved().playing['r:h1'].ball;
    fireEvent.click(ui.getByRole('button',{name:'Next',exact:true}));
    assert.ok(ui.getByRole('heading',{name:'7 iron',exact:true}));
    fireEvent.click(ui.getByRole('button',{name:'Previous',exact:true}));
    assert.deepEqual(saved().playing['r:h1'].ball,ball);
    const svg=ui.getByRole('img',{name:/^Hole 1/});
    const redCircle=svg.querySelector('circle[fill="#f23937"]')!;
    const tx=Number(redCircle.getAttribute('cx')),ty=Number(redCircle.getAttribute('cy'));
    fireEvent.pointerDown(svg,{pointerId:20,clientX:tx,clientY:ty});
    fireEvent.pointerUp(svg,{pointerId:20,clientX:tx,clientY:ty});
    const overlappingTarget=saved().playing['r:h1'].target;
    const yellow=ui.getByRole('button',{name:'Lock yellow target on map'});
    fireEvent.pointerDown(yellow,{pointerId:21,clientX:tx,clientY:ty});
    fireEvent.pointerUp(svg,{pointerId:21,clientX:tx,clientY:ty});
    assert.ok(ui.getByRole('button',{name:'Unlock yellow target',exact:true}));
    const redHandle=ui.getByRole('button',{name:'Red tee'});
    assert.equal(redHandle.getAttribute('pointer-events'),'auto','locked yellow cannot intercept red');
    assert.ok(yellow.compareDocumentPosition(redHandle)&dom.window.Node.DOCUMENT_POSITION_FOLLOWING,'red renders above locked yellow');
    assert.equal(redHandle.querySelector('circle:last-child')!.getAttribute('r'),'4','visible dots are half their previous radius');
    fireEvent.pointerDown(redHandle,{pointerId:22,clientX:tx,clientY:ty});
    fireEvent.pointerMove(svg,{pointerId:22,clientX:tx+12,clientY:ty-12});
    fireEvent.pointerUp(svg,{pointerId:22,clientX:tx+12,clientY:ty-12});
    assert.ok(ui.getByRole('button',{name:'Save positions'}));
    assert.deepEqual(saved().playing['r:h1'].target,overlappingTarget,'red dragging does not move yellow');
    fireEvent.click(ui.getByRole('button',{name:'Cancel',exact:true}));
    fireEvent.click(ui.getByRole('button',{name:'Zoom in',exact:true}));
    assert.ok(ui.getByText('1.5×',{exact:true}));
    assert.deepEqual(saved().playing['r:h1'].target,overlappingTarget,'zoom does not alter shot coordinates');
    fireEvent.click(ui.getByRole('button',{name:'Whole hole',exact:true}));
    assert.ok(ui.getByText('1.0×',{exact:true}));
    fireEvent.pointerDown(svg,{pointerId:31,clientX:100,clientY:200});
    fireEvent.pointerDown(svg,{pointerId:32,clientX:200,clientY:200});
    fireEvent.pointerMove(svg,{pointerId:32,clientX:250,clientY:200});
    fireEvent.pointerUp(svg,{pointerId:31,clientX:100,clientY:200});
    fireEvent.pointerUp(svg,{pointerId:32,clientX:250,clientY:200});
    assert.ok(ui.getByText('1.5×',{exact:true}));
    assert.deepEqual(saved().playing['r:h1'].target,overlappingTarget,'pinch fingers never place a target');
    fireEvent.click(ui.getByRole('button',{name:'Whole hole',exact:true}));
    const originalHole = saved().holes.find((h:any)=>h.id==='h1');
    fireEvent.click(ui.getByRole('button',{name:'Move red / green dots'}));
    fireEvent.pointerDown(ui.getByRole('button',{name:'Red tee'}),{pointerId:7,clientX:160,clientY:480,buttons:1});
    fireEvent.pointerMove(ui.getByRole('img',{name:/^Hole 1/}),{pointerId:7,clientX:180,clientY:450,buttons:1});
    fireEvent.pointerUp(ui.getByRole('img',{name:/^Hole 1/}),{pointerId:7});
    assert.equal(saved().holes.find((h:any)=>h.id==='h1').teeMarker,undefined,'drag is a draft until saved');
    fireEvent.click(ui.getByRole('button',{name:'Cancel',exact:true}));
    assert.equal(saved().holes.find((h:any)=>h.id==='h1').teeMarker,undefined,'cancel leaves saved positions intact');
    fireEvent.click(ui.getByRole('button',{name:'Move red / green dots'}));
    fireEvent.keyDown(ui.getByRole('button',{name:'Red tee'}),{key:'ArrowRight',shiftKey:true});
    fireEvent.click(ui.getByRole('button',{name:'Move green',exact:true}));
    fireEvent.keyDown(ui.getByRole('button',{name:'Green centre'}),{key:'ArrowLeft',shiftKey:true});
    fireEvent.click(ui.getByRole('button',{name:'Save positions'}));
    const corrected=saved().holes.find((h:any)=>h.id==='h1');
    assert.deepEqual(corrected.teeMarker,[5,0]);
    assert.deepEqual(corrected.greenMarker,[-5,500]);
    assert.deepEqual(corrected.tee,originalHole.tee,'GPS anchor stays fixed');
    assert.deepEqual(corrected.shape,originalHole.shape,'moving dots never relocates hazards or outlines');
    assert.deepEqual(saved().playing['r:h1'].ball,ball,'a ball already on the course is preserved');
    assert.equal(ui.queryByRole('button',{name:'Save positions'}),null,'editing finishes after saving');
    ui.unmount();
    const again=render(React.createElement(Play,{go:()=>{}}));
    assert.ok(again.getByText('Ball set on map',{exact:true}));
    again.unmount();
  } finally {cleanup();dom.window.close();}
});
